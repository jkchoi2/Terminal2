      <Section id="files" title="12. 파일 저장·불러오기">
        <ul>
          <li>파일 대화상자는 마지막으로 쓴 폴더에서 열립니다(다시 실행해도 기억).</li>
          <li>
            매크로·R/R·차트 설정은 불러오거나 저장한 파일과 <b>연결</b>됩니다. 아래쪽에 파일 이름과 <b>● 수정됨</b>이 표시되고,
            <b>저장</b>은 그 파일에 바로 덮어씁니다.
          </li>
          <li>수정된 상태에서 다른 파일을 불러오면 [저장 후 불러오기 / 저장 안 함 / 취소]를 묻습니다.</li>
          <li>불러오기 직전 목록은 실행폴더\backup 에 자동 보관됩니다(종류별 최근 20개).</li>
          <li>수신창 우클릭 → <b>저장</b>: 지금 수신창에 남아 있는 내용(최근 5,000건)을 텍스트 파일로 저장합니다.</li>
          <li>
            수신창 툴바 <b>● LOG</b>: 켜 두면 연결할 때마다 <code>실행폴더\Log\Serial|TcpClient|TcpServer|Udp\</code> 에 새 파일(날짜_시각_대상.log)을
            만들어 송수신을 계속 기록합니다(수신창 5,000건 제한과 무관, 10MB마다 다음 파일). 점 표시: 회색 = 꺼짐, 빨간 테두리 = 연결하면
            기록, 빨간 점 = 기록 중. <b>▾</b>에서 현재 파일, 보관 기간(지난 파일 자동 삭제), 로그 폴더 열기를 설정합니다.
          </li>
          <li>
            송신창 <b>파일…</b>: 파일 내용을 <b>줄 단위</b>(줄 끝 없음/CR/LF/CRLF, 줄을 그대로 또는 HEX 문자열로), <b>파일 전체</b>,
            <b>N바이트씩</b> 나눠 지정한 간격(ms)으로 보냅니다. 미리보기로 조각 수를 확인하고, 보내는 중에는 송신창 아래에 진행
            상황과 <b>중지</b> 버튼이 표시됩니다. 연결이 끊기면 멈춥니다.
          </li>
        </ul>
      </Section>

