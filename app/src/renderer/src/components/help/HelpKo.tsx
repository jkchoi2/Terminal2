      <Section id="rr" title="10. Request / Response (자동 응답)">
        <p>수신한 패킷이 규칙의 Request 패턴과 일치하면 Response를 자동으로 보냅니다. 장비 시뮬레이터로 쓸 때 유용합니다.</p>
        <ol>
          <li>수신창 툴바 <b>R/R</b> → <b>+ 추가</b>.</li>
          <li>Request: 형식(ASCII/HEX)과 패턴 입력. 패턴은 수신 패킷 <b>전체</b>와 비교합니다.</li>
          <li>Response: 보낼 데이터, +CR/+LF, 지연(ms), 필요하면 체크섬/Trailer.</li>
          <li>왼쪽 아래 <b>매칭 테스트</b>에 예상 수신 데이터를 넣어 어느 규칙이 일치하는지, 응답이 무엇인지 확인.</li>
          <li>
            <b>기능 전체 활성화</b> 켜고 확인. 규칙별 On/Off 가능. 위에서부터 첫 번째로 일치한 규칙 하나만 응답합니다. Hit 열은 일치
            횟수.
          </li>
        </ol>
        <p>
          <b>수신 체크섬 검증</b>을 켜면 요청 패킷의 체크섬이 맞을 때만 응답합니다. "체크섬 위치"는 수신 패킷 안에서 체크섬이 있는
          offset입니다(예: <code>… CS ETX</code> 이면 -2).
        </p>
        <p>
          응답 HEX에서 <code>R[n]</code>은 요청 패킷의 n번째 바이트를 그대로 넣습니다(주소·순번 되돌려주기). 예: 요청{' '}
          <code>02 ?? 05 * 03</code>, 응답 <code>02 R[1] 06 03</code>
        </p>
      </Section>

